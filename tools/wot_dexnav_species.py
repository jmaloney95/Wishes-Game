"""DexNav search-level slots.

Expansion's per-species search levels want a byte per species (~1.7 KB) and
SaveBlock3 doesn't have it. WoT keeps a byte only for species that can appear
in a wild encounter table. This writes the list:

  include/constants/wot_dexnav.h       WOT_DEXNAV_SPECIES_COUNT
  src/data/wot_dexnav_species.h        sWotDexNavSpecies[] (slot -> species)

APPEND-ONLY: a slot is a byte in players' saves, so species already listed
keep their slot (even if they leave the tables) and new ones go on the end.
Re-run after adding wild species:  python3 tools/wot_dexnav_species.py
"""
import json
import os
import re

TABLES = 'src/data/wild_encounters.json'
OUT_LIST = 'src/data/wot_dexnav_species.h'
OUT_COUNT = 'include/constants/wot_dexnav.h'

existing = []
if os.path.exists(OUT_LIST):
    existing = re.findall(r'\b(SPECIES_\w+),', open(OUT_LIST).read())

found = []
data = json.load(open(TABLES))
for group in data['wild_encounter_groups']:
    if group.get('label') != 'gWildMonHeaders':
        continue
    for enc in group['encounters']:
        for field, val in enc.items():
            if isinstance(val, dict) and 'mons' in val:
                for mon in val['mons']:
                    if mon['species'] not in found:
                        found.append(mon['species'])

slots = list(existing)
for sp in sorted(found):
    if sp not in slots:
        slots.append(sp)

with open(OUT_LIST, 'w', newline='\n') as f:
    f.write('// GENERATED by tools/wot_dexnav_species.py -- append-only, do not reorder.\n')
    f.write('// DexNav search-level slot -> species (a slot is a byte in SaveBlock3).\n\n')
    f.write('static const u16 sWotDexNavSpecies[WOT_DEXNAV_SPECIES_COUNT] =\n{\n')
    for sp in slots:
        f.write('    %s,\n' % sp)
    f.write('};\n')

with open(OUT_COUNT, 'w', newline='\n') as f:
    f.write('#ifndef GUARD_CONSTANTS_WOT_DEXNAV_H\n#define GUARD_CONSTANTS_WOT_DEXNAV_H\n\n')
    f.write('// GENERATED by tools/wot_dexnav_species.py: species with a DexNav search-level slot.\n')
    f.write('#define WOT_DEXNAV_SPECIES_COUNT %d\n\n#endif // GUARD_CONSTANTS_WOT_DEXNAV_H\n' % len(slots))
print('%d slots (%d new)' % (len(slots), len(slots) - len(existing)))
