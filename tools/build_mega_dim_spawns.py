#!/usr/bin/env python3
"""Mega Dimension overworld wild Pokemon: SEED placeholder objects for a new map.

Since round 125 the game uses the placeholder objects exactly where they sit in
porymap (every 3, in map order, are one group), so this tool only seeds a
dimension map that has NO placeholders yet -- maps that already have them are
left alone, so porymap placements are never overwritten.

For every dimension map (data/maps/MegaDimension_*), reads the layout it shares
with its real map and finds the areas its visible wild Pokemon stand in:

  * the 4-connected patches of tall/long grass with at least 3 tiles, or
  * on maps with no grass (Shin Tokyo, Star Summit), open-ground areas: the
    cells of a 16x16 grid holding at least 20 walkable tiles.

At most MAX_AREAS areas per map (largest first), each with up to MAX_TILES
candidate tiles. A candidate is walkable, has 3+ walkable neighbours (so a
Pokemon standing on it rarely plugs a corridor -- and battling it removes it
anyway), and is not on a portal/Mega slot or the tile south of one (where the
player arrives), nor on the real map's warps or triggers.

Writes (only into dimension maps without placeholders):
  data/maps/MegaDimension_*/map.json -- 3 placeholder objects per area
    (script MegaDim_EventScript_WildMon, hide flags FLAG_TEMP_3 upward, one
    flag each); the game deals their species and shininess every visit.

The slots are parsed from sDimMaps in src/wot_mega_dimension.c, so re-run this
after changing a slot, a layout, or adding a dimension map.

Usage: python tools/build_mega_dim_spawns.py
"""
import glob
import json
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GRASS_BEHAVIORS = {2, 3, 201, 240}   # MB_TALL_GRASS, MB_LONG_GRASS, MB_CYCLING_ROAD_PULL_DOWN_GRASS, MB_DISTORTION_GRASS (compiled probe)
MON_PER_AREA = 3
MAX_AREAS = 8
MAX_TILES = 16
FIRST_TEMP_FLAG = 3                  # FLAG_TEMP_1 = the Mega, FLAG_TEMP_2 = the rival
MIN_GRASS_PATCH = 3
CELL = 16
MIN_CELL_WALKABLE = 20
NUM_METATILES_IN_PRIMARY = 512


def rd(path):
    return open(os.path.join(ROOT, path), encoding='utf-8', newline='').read()


def tileset_attr_paths():
    headers = rd('src/data/tilesets/headers.h')
    metatiles = rd('src/data/tilesets/metatiles.h')
    sym2path = dict(re.findall(r'const u16 (gMetatileAttributes_\w+)\[\] = INCBIN_U16\("([^"]+)"\)', metatiles))
    out = {}
    for name, body in re.findall(r'const struct Tileset (gTileset_\w+) =\s*\{(.*?)\};', headers, re.S):
        m = re.search(r'\.metatileAttributes = (gMetatileAttributes_\w+)', body)
        if m and m.group(1) in sym2path:
            out[name] = sym2path[m.group(1)]
    return out


def dim_slots():
    src = rd('src/wot_mega_dimension.c')
    block = src[src.index('static const struct MegaDimMap sDimMaps[]'):]
    block = block[:block.index('};')]
    rows = {}
    for m in re.finditer(r'\{\s*(?:FLAG_\w+|0)\s*,\s*(MAP_MEGA_DIMENSION_\w+)\s*,\s*\{((?:\s*\{[^}]*\}\s*,?)+)\}\s*\}', block):
        slots = [tuple(int(v) for v in t.split(',')) for t in re.findall(r'\{([^{}]*)\}', m.group(2))]
        rows[m.group(1)] = [(x, y) for x, y, _ in slots]
    return rows


def main():
    layouts = {l['id']: l for l in json.loads(rd('data/layouts/layouts.json'))['layouts'] if 'id' in l}
    attrs_path = tileset_attr_paths()
    slots = dim_slots()
    all_maps = {}
    for p in glob.glob(os.path.join(ROOT, 'data/maps/*/map.json')):
        m = json.load(open(p, encoding='utf-8'))
        all_maps[p] = m

    header = [
        '// Generated by tools/build_mega_dim_spawns.py -- do not edit by hand.',
        '// Where the Mega Dimension\'s visible wild Pokemon may stand, per dimension map.',
        '',
    ]
    table = []

    for p, m in sorted(all_maps.items()):
        if not m['name'].startswith('MegaDimension_'):
            continue
        mapconst = m['id']
        L = layouts[m['layout']]
        W, H = L['width'], L['height']
        blk = open(os.path.join(ROOT, L['blockdata_filepath']), 'rb').read()
        v = struct.unpack('<%dH' % (W * H), blk[:W * H * 2])
        prim = open(os.path.join(ROOT, attrs_path[L['primary_tileset']]), 'rb').read()
        sec = open(os.path.join(ROOT, attrs_path[L['secondary_tileset']]), 'rb').read()
        prim = struct.unpack('<%dH' % (len(prim) // 2), prim)
        sec = struct.unpack('<%dH' % (len(sec) // 2), sec)

        def behavior(x, y):
            mt = v[y * W + x] & 0x3FF
            a = prim[mt] if mt < NUM_METATILES_IN_PRIMARY else (sec[mt - NUM_METATILES_IN_PRIMARY] if mt - NUM_METATILES_IN_PRIMARY < len(sec) else 0)
            return a & 0xFF

        def col(x, y): return (v[y * W + x] >> 10) & 3
        def elev(x, y): return v[y * W + x] >> 12
        def walk(x, y): return 0 <= x < W and 0 <= y < H and col(x, y) == 0 and elev(x, y) != 1

        # the real map's warps/triggers + this map's slots (and arrival tiles)
        bad = set()
        for q, other in all_maps.items():
            if other['layout'] == m['layout'] and not other['name'].startswith('MegaDimension_'):
                for w in other.get('warp_events') or []:
                    bad.add((w['x'], w['y']))
                for c in other.get('coord_events') or []:
                    bad.add((c['x'], c['y']))
        for (sx, sy) in slots.get(mapconst, []):
            bad.add((sx, sy))
            bad.add((sx, sy + 1))

        def neighbours(x, y):
            return sum(walk(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))

        def ok(x, y):
            return walk(x, y) and (x, y) not in bad and neighbours(x, y) >= 3

        grass = {(x, y) for y in range(H) for x in range(W) if walk(x, y) and behavior(x, y) in GRASS_BEHAVIORS}
        areas = []
        if grass:
            seen = set()
            for start in sorted(grass, key=lambda t: (t[1], t[0])):
                if start in seen:
                    continue
                comp, stack = [], [start]
                seen.add(start)
                while stack:
                    x, y = stack.pop()
                    comp.append((x, y))
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        n = (x + dx, y + dy)
                        if n in grass and n not in seen:
                            seen.add(n)
                            stack.append(n)
                if len(comp) >= MIN_GRASS_PATCH:
                    areas.append(comp)
            kind = 'grass'
        else:
            for cy in range(0, H, CELL):
                for cx in range(0, W, CELL):
                    comp = [(x, y) for y in range(cy, min(cy + CELL, H)) for x in range(cx, min(cx + CELL, W)) if walk(x, y)]
                    if len(comp) >= MIN_CELL_WALKABLE:
                        areas.append(comp)
            kind = 'open ground'

        picked = []
        for comp in sorted(areas, key=len, reverse=True):
            cands = sorted([t for t in comp if ok(*t)], key=lambda t: (t[1], t[0]))
            if len(cands) < MON_PER_AREA:
                continue
            if len(cands) > MAX_TILES:
                step = len(cands) / MAX_TILES
                cands = [cands[int(i * step)] for i in range(MAX_TILES)]
            picked.append(cands)
            if len(picked) == MAX_AREAS:
                break

        label = m['name']
        for ai, cands in enumerate(picked):
            header.append('static const struct MegaDimSpawnTile s%s_Area%d[] = {%s};' % (
                label, ai, ', '.join('{%d, %d, %d}' % (x, y, elev(x, y)) for x, y in cands)))
        if picked:
            header.append('static const struct MegaDimSpawnArea s%s_Areas[] = {' % label)
            for ai, cands in enumerate(picked):
                header.append('    {s%s_Area%d, ARRAY_COUNT(s%s_Area%d)},' % (label, ai, label, ai))
            header.append('};')
            table.append('    {%s, s%s_Areas, ARRAY_COUNT(s%s_Areas)},' % (mapconst, label, label))
        header.append('')

        # placeholders in the dimension map -- never touch porymap-placed ones
        if any(o['script'] == 'MegaDim_EventScript_WildMon' for o in m['object_events']):
            print('%-30s kept (already has placeholders)' % label)
            continue
        objs = list(m['object_events'])
        n = 0
        for ai, cands in enumerate(picked):
            for j in range(MON_PER_AREA):
                x, y = cands[j * len(cands) // MON_PER_AREA]
                objs.append({
                    "graphics_id": "OBJ_EVENT_GFX_SPECIES(FOONGUS)",
                    "x": x, "y": y, "elevation": elev(x, y),
                    "movement_type": "MOVEMENT_TYPE_LOOK_AROUND",
                    "movement_range_x": 0, "movement_range_y": 0,
                    "trainer_type": "TRAINER_TYPE_NONE",
                    "trainer_sight_or_berry_tree_id": "0",
                    "script": "MegaDim_EventScript_WildMon",
                    "flag": "FLAG_TEMP_%X" % (FIRST_TEMP_FLAG + n)
                })
                n += 1
        assert FIRST_TEMP_FLAG + n - 1 <= 0x1F and len(objs) <= 64, (label, n, len(objs))
        m['object_events'] = objs
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            json.dump(m, f, indent=2)
            f.write('\n')
        print('%-30s %-11s %d areas -> %d wild objects' % (label, kind, len(picked), n))

    pass

if __name__ == '__main__':
    main()
