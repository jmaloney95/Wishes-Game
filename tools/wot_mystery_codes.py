"""Mystery Code gift table.

Each Mega card carries one fixed Mystery Code. Typing it at the code NPC
(src/wot_mystery_code.c) gives that card's Pokemon once per save. The card
list is a JSON file shared with the website, rows like:

  {"n": 1, "slug": "butterfree", "name": "Mega Butterfree", "code": "FRRKESMV",
   "species": "SPECIES_BUTTERFREE", "item": "ITEM_BUTTERFRITE"}

and an optional "note" for a card that is not a plain gift. The site's card
data (cards.json, rows with "slug", "code" and "finish") gives each card's
rarity: the rare and secret finishes make the NPC say "Epic pull!" instead of
"Nice pull!". This writes

  src/data/wot_mystery_codes.h    sWotMysteryCodes[] and WOT_MYSTERY_CODE_COUNT

A row's card number n is its bit in SaveBlock3's wotMysteryCodesUsed, so the
table is APPEND-ONLY: a card already in the header must keep its code,
species and item. New cards take the next numbers.

  python3 tools/wot_mystery_codes.py <mystery_codes.json> <cards.json>          write the header
  python3 tools/wot_mystery_codes.py <mystery_codes.json> <cards.json> --check  fail if it is stale
"""
import json
import os
import re
import sys

OUT = 'src/data/wot_mystery_codes.h'
CODE_LENGTH = 8
ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ'

# Cards that are not a plain gift, by slug. A card with a "note" must be
# listed here, so a new special card can't slip through as a plain one.
SPECIAL_CARDS = {
    # Mega Rayquaza needs no stone: it Mega Evolves while it knows Dragon Ascent.
    'rayquaza_shiny': {'shiny': True, 'move': 'MOVE_DRAGON_ASCENT'},
    'ho_oh_shadow': {'shadow': True},
}

# The site's rarity tiers by finish: rare and secret cards are an "Epic pull!".
RARE_FINISHES = {'Rainbow swirl', 'Gold', 'Cosmos'}
SECRET_FINISHES = {'Manga blaze', 'Shadow'}


def fail(msg):
    sys.exit('wot_mystery_codes.py: ' + msg)


def load_cards(path):
    data = json.load(open(path, encoding='utf-8'))
    if data.get('alphabet', ALPHABET) != ALPHABET or data.get('length', CODE_LENGTH) != CODE_LENGTH:
        fail('the JSON uses a different code alphabet or length')
    cards = sorted(data['cards'], key=lambda c: c['n'])
    if [c['n'] for c in cards] != list(range(1, len(cards) + 1)):
        fail('card numbers must run 1..N with no gaps')
    seen = set()
    for c in cards:
        code = c['code']
        if len(code) != CODE_LENGTH or any(ch not in ALPHABET for ch in code):
            fail('card %d: bad code %r' % (c['n'], code))
        if code in seen:
            fail('card %d: code %s is used twice' % (c['n'], code))
        seen.add(code)
        if not re.fullmatch(r'SPECIES_\w+', c['species']) or not re.fullmatch(r'ITEM_\w+', c['item']):
            fail('card %d: bad species or item constant' % c['n'])
        if not re.fullmatch(r"[A-Za-z0-9 .'-]{1,%d}" % 15, c['name']):
            fail('card %d: name %r must be 1-15 plain characters' % (c['n'], c['name']))
        if c.get('note') and c['slug'] not in SPECIAL_CARDS:
            fail('card %d (%s) has a note; add it to SPECIAL_CARDS' % (c['n'], c['slug']))
    return cards


def load_finishes(path, cards):
    """slug -> finish, checked against the code list."""
    site = {c['slug']: c for c in json.load(open(path, encoding='utf-8'))['cards']}
    finishes = {}
    for c in cards:
        row = site.get(c['slug'])
        if row is None or not row.get('finish'):
            fail('card %d (%s) has no finish in %s' % (c['n'], c['slug'], path))
        if row.get('code', c['code']) != c['code']:
            fail('card %d (%s): the site shows code %s, the code list has %s' % (c['n'], c['slug'], row['code'], c['code']))
        finishes[c['slug']] = row['finish']
    return finishes


def existing_rows():
    """card number -> (code, species, item) from the current header."""
    rows = {}
    if os.path.exists(OUT):
        for m in re.finditer(r'\[(\d+) - 1\] = \{ "(\w+)", (SPECIES_\w+), (ITEM_\w+)', open(OUT).read()):
            rows[int(m.group(1))] = (m.group(2), m.group(3), m.group(4))
    return rows


def render(cards, finishes):
    lines = [
        '// GENERATED by tools/wot_mystery_codes.py from the Mega card list -- do not edit.',
        '// Append-only: card n is bit n - 1 of gSaveBlock3Ptr->wotMysteryCodesUsed.',
        '',
        '#define WOT_MYSTERY_CODE_COUNT %d' % len(cards),
        '',
        'static const struct WotMysteryCodeGift sWotMysteryCodes[WOT_MYSTERY_CODE_COUNT] =',
        '{',
    ]
    for c in cards:
        extra = SPECIAL_CARDS.get(c['slug'], {})
        finish = finishes[c['slug']]
        fields = [
            '"%s"' % c['code'],
            c['species'],
            c['item'],
            extra.get('move', 'MOVE_NONE'),
            'TRUE' if extra.get('shiny') else 'FALSE',
            'TRUE' if extra.get('shadow') else 'FALSE',
            'TRUE' if finish in RARE_FINISHES | SECRET_FINISHES else 'FALSE',
            'COMPOUND_STRING("%s")' % c['name'],
        ]
        lines.append('    [%d - 1] = { %s }, // %s, %s' % (c['n'], ', '.join(fields), c['slug'], finish))
    lines += ['};', '']
    return '\n'.join(lines)


def main():
    args = [a for a in sys.argv[1:] if a != '--check']
    if len(args) != 2:
        fail('usage: python3 tools/wot_mystery_codes.py <mystery_codes.json> <cards.json> [--check]')
    cards = load_cards(args[0])
    finishes = load_finishes(args[1], cards)
    old = existing_rows()
    for c in cards:
        was = old.pop(c['n'], None)
        if was and was != (c['code'], c['species'], c['item']):
            fail('card %d changed (%s -> %s): saved bits would point at the wrong gift'
                 % (c['n'], '/'.join(was), '/'.join((c['code'], c['species'], c['item']))))
    if old:
        fail('cards %s are in the header but not the JSON; rows are never removed' % sorted(old))
    text = render(cards, finishes)
    if '--check' in sys.argv:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            fail('%s is out of date; re-run without --check' % OUT)
        print('%s is up to date (%d codes)' % (OUT, len(cards)))
        return
    with open(OUT, 'w', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d codes)' % (OUT, len(cards)))


if __name__ == '__main__':
    main()
